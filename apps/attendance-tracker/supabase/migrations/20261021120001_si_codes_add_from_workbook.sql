-- More S.I. codes, from the "SI Codes" sheet of Book1.xlsx.
--
-- 3052 rows, added to the 5542 already seeded. Add, not replace: every
-- statement below carries ON CONFLICT DO NOTHING, so a code already in
-- the table keeps the title it has and nothing here can overwrite it.
--
-- Why the conflict clause does the deciding rather than a pre-filtered
-- list: this file was compared against the seeding migration, but the
-- live table is what matters and codes may have been added to it since.
-- Letting the database skip what it already holds is right whatever
-- state it is in, and makes the whole thing safe to run twice.
--
-- Two things to know about the data.
--
-- 523 of these codes are five digits, where every code already in the
-- table is six. They were NOT zero-padded. The existing data has no
-- codes beginning with 0 at all -- first digits run 1 to 9 -- so a
-- padded 0xxxxx range would join onto nothing, and the five-digit codes
-- spread across the same first digits and mostly end in 00, which reads
-- as a coarser level of the same scheme rather than a truncation.
--
-- 31 six-digit codes already exist with an entirely different title --
-- 132120 is a food production manager here and a senior teacher in the
-- file, and the other 30 are no closer. Those 31 are skipped, so this
-- migration does not act on the disagreement. It is flagged because two
-- sources disagreeing on 31 codes may mean they are different vintages
-- of the standard, which would matter for codes already stored against
-- employees.
-- =====================================================================

