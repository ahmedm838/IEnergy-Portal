-- --- 2. Financial grants -----------------------------------------------

create table if not exists public.financial_grants (
  id          smallint generated by default as identity primary key,
  name        text          not null unique check (btrim(name) <> ''),
  amount      numeric(12,2) not null check (amount > 0),
  attachments text          not null check (btrim(attachments) <> ''),
  sort_order  smallint      not null default 0
);

comment on table public.financial_grants is
  'Grants an employee can request on the financial grant form: picking one fills in its amount and attachments. Super admins edit it in Settings.';

alter table public.financial_grants enable row level security;

drop policy if exists financial_grants_read on public.financial_grants;
create policy financial_grants_read on public.financial_grants
  for select to authenticated
  using (my_role() <> 'no_access'::app_role);

drop policy if exists financial_grants_write on public.financial_grants;
create policy financial_grants_write on public.financial_grants
  for all to authenticated
  using (is_super_admin())
  with check (is_super_admin());

grant select, insert, update, delete on public.financial_grants to authenticated;

-- --- 3. app_lookups ----------------------------------------------------

create or replace function app_lookups()
returns jsonb
language sql
stable
-- security invoker is the default; named so nobody "tidies" it to definer
security invoker
set search_path = public
as $$
  select jsonb_build_object(
    'sites', coalesce((
      select jsonb_agg(to_jsonb(s) order by s.sort_order, s.id) from sites s
    ), '[]'::jsonb),

    'sectors', coalesce((
      select jsonb_agg(to_jsonb(s) order by s.sort_order, s.id) from sectors s
    ), '[]'::jsonb),

    'departments', coalesce((
      select jsonb_agg(
               jsonb_build_object(
                 'id', d.id,
                 'name', d.name,
                 'name_ar', d.name_ar,
                 'sector_id', d.sector_id,
                 'sort_order', d.sort_order,
                 -- The embed PostgREST used to return: null when the
                 -- department has no sector, never a missing department.
                 'sectors', (
                   select jsonb_build_object('id', sec.id, 'name', sec.name, 'name_ar', sec.name_ar)
                   from sectors sec where sec.id = d.sector_id
                 )
               )
               order by d.sort_order, d.id
             )
      from departments d
    ), '[]'::jsonb),

    'statuses', coalesce((
      select jsonb_agg(to_jsonb(s) order by s.sort_order, s.id)
      from employee_statuses s
    ), '[]'::jsonb),

    'types', coalesce((
      select jsonb_agg(to_jsonb(t) order by t.sort_order, t.id)
      from attendance_types t
    ), '[]'::jsonb),

    'bus_routes', coalesce((
      select jsonb_agg(to_jsonb(b) order by b.sort_order, b.id)
      from bus_routes b
    ), '[]'::jsonb),

    'levels', coalesce((
      select jsonb_agg(to_jsonb(l) order by l.sort_order, l.id)
      from employee_levels l
    ), '[]'::jsonb),

    'financial_grants', coalesce((
      select jsonb_agg(to_jsonb(g) order by g.sort_order, g.id)
      from financial_grants g
    ), '[]'::jsonb),

    'settings', coalesce((
      select jsonb_agg(to_jsonb(a) order by a.key) from app_settings a
    ), '[]'::jsonb)
  );
$$;

comment on function app_lookups() is
  'All reference data in one call, with the caller''s own row-level security applied. Replaces separate table reads from the client.';

grant execute on function app_lookups() to authenticated;
