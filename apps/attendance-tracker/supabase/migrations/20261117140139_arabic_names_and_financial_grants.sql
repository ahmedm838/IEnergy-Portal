-- =====================================================================
-- Arabic names for departments and sectors, and the financial grants
-- table.
--
-- 1. departments.name_ar and sectors.name_ar, editable on the Settings
--    page. The forms (HR Documents, Employee Documents) print the
--    department in Arabic, and only in Arabic: a department without an
--    Arabic name is reported as missing data on the form instead of
--    printing its English name in an Arabic document.
--
--    20261112160001 added departments.name_ar but never reached the
--    database, so the column is added here (if not exists) and its seed
--    is repeated, extended to every department and sector that exists
--    now. These are suggested translations: correct any in Settings.
--
-- 2. financial_grants: the grants an employee can ask for on the
--    financial grant request (طلب صرف منحة مالية) -- name, amount and the
--    attachments it needs. Picking one on the form fills in the amount
--    and the attachments. Everyone signed in reads it; only a super admin
--    adds, edits or removes one, as with the other reference tables.
--
-- 3. app_lookups() returns the Arabic names and the grants, so Settings
--    reads them in the call it already makes.
-- =====================================================================

